# ---------------------------------------------------------------------
# 1. 데이터 살펴보기 (R에 기본 내장된 cars 데이터: 자동차 속도와 제동거리 50건)
# ---------------------------------------------------------------------
head(cars)       # 앞 6줄 보기
str(cars)        # 구조: 몇 행, 몇 열, 각 열의 자료형
summary(cars)    # 최소값, 1사분위수(Q1), 중앙값, 평균, 3사분위수(Q3), 최대값

# 상자그림: 가운데 굵은 선 = 중앙값, 상자 = Q1~Q3, 바깥 동그라미 = 이상값
boxplot(cars$dist, main = "제동거리 상자그림")

# 이상값 기준 직접 계산해 보기 (Q1 - 1.5*IQR, Q3 + 1.5*IQR)
q1 <- quantile(cars$dist, 0.25)
q3 <- quantile(cars$dist, 0.75)
iqr <- q3 - q1
c(아래기준 = q1 - 1.5 * iqr, 위기준 = q3 + 1.5 * iqr)


# ---------------------------------------------------------------------
# 2. 상관분석: 속도와 제동거리는 같이 움직일까?
# ---------------------------------------------------------------------
cor(cars$speed, cars$dist)            # 피어슨 상관계수 (약 0.81 → 강한 양의 상관)
cor.test(cars$speed, cars$dist)       # p-value < 0.05 → "상관이 없다"는 귀무가설 기각
cor(cars$speed, cars$dist, method = "spearman")   # 스피어만(순위 기반)


# ---------------------------------------------------------------------
# 3. 단순 선형 회귀 ⭐ (시험에 가장 많이 나오는 출력)
# ---------------------------------------------------------------------
model <- lm(dist ~ speed, data = cars)   # lm = linear model(선형 모형)
summary(model)
# 해석 포인트
#  - Estimate(speed) = 3.9324   → 속도 1 증가 시 제동거리 약 3.93 증가
#  - Pr(>|t|) 옆 별(***)         → 변수가 유의함 (p < 0.001)
#  - Multiple R-squared 0.6511  → 제동거리 변동의 65%를 속도로 설명
#  - F-statistic의 p-value      → 모형 전체가 유의한지
#  - 48 degrees of freedom      → n(50) - 변수 수(1) - 1

plot(cars, main = "속도 vs 제동거리")
abline(model, col = "red")               # 회귀 직선 그리기

par(mfrow = c(2, 2)); plot(model); par(mfrow = c(1, 1))
# 잔차 진단 그래프 4개. 특히 "Normal Q-Q"에서 점들이 직선 위에 있으면 정규성 만족


# ---------------------------------------------------------------------
# 4. 다중 회귀 + 변수 선택 (mtcars: 자동차 32종의 연비 등)
# ---------------------------------------------------------------------
full <- lm(mpg ~ ., data = mtcars)       # . = 나머지 모든 변수를 독립변수로
summary(full)                            # 변수가 많아서 대부분 유의하지 않게 나옴 (다중공선성 의심)

step_model <- step(full, direction = "backward")   # 후진 제거법, AIC가 작아지는 방향으로
summary(step_model)
# direction = "forward"(전진), "both"(단계적)도 있음


# ---------------------------------------------------------------------
# 5. 가설검정 모음
# ---------------------------------------------------------------------
# (1) 독립표본 t검정: 자동/수동 변속기(am) 차의 연비 평균이 다른가?
t.test(mpg ~ am, data = mtcars)          # p-value < 0.05 → 평균이 다르다

# (2) 대응표본 t검정: 수면제 두 종류를 같은 사람 10명에게 (sleep 데이터)
t.test(sleep$extra[sleep$group == 1],
       sleep$extra[sleep$group == 2], paired = TRUE)

# (3) 정규성 검정: p-value > 0.05 이면 "정규분포를 따른다"(귀무가설) 기각 못함
shapiro.test(cars$dist)

# (4) 카이제곱 독립성 검정: 기어 수(gear)와 변속기(am)는 관련이 있나?
table(mtcars$gear, mtcars$am)            # 교차표
chisq.test(table(mtcars$gear, mtcars$am))  # 칸이 작아 경고가 뜰 수 있음(정상)

# (5) 분산분석(ANOVA): 붓꽃 품종 3개의 꽃받침 길이 평균이 다른가?
summary(aov(Sepal.Length ~ Species, data = iris))


# ---------------------------------------------------------------------
# 6. 로지스틱 회귀: 무게(wt)로 수동변속기(am=1)일 확률 예측
# ---------------------------------------------------------------------
logit <- glm(am ~ wt, data = mtcars, family = binomial)
summary(logit)
exp(coef(logit))    # 오즈비: wt가 1 증가하면 오즈가 몇 배가 되는지 (1보다 작으면 감소)


# ---------------------------------------------------------------------
# 7. 분류 평가 — 혼동행렬 지표를 손 계산처럼 해 보기
# ---------------------------------------------------------------------
TP <- 40; FN <- 10; FP <- 20; TN <- 30
정확도 <- (TP + TN) / (TP + TN + FP + FN)
정밀도 <- TP / (TP + FP)
재현율 <- TP / (TP + FN)
특이도 <- TN / (TN + FP)
F1 <- 2 * 정밀도 * 재현율 / (정밀도 + 재현율)
round(c(정확도 = 정확도, 정밀도 = 정밀도, 재현율 = 재현율, 특이도 = 특이도, F1 = F1), 3)


# ---------------------------------------------------------------------
# 8. 의사결정나무 (rpart: R 설치 시 기본 포함 패키지)
# ---------------------------------------------------------------------
library(rpart)
tree <- rpart(Species ~ ., data = iris)
print(tree)                              # 분기 규칙 텍스트로 보기
plot(tree, margin = 0.1); text(tree)     # 나무 그림
pred <- predict(tree, iris, type = "class")
table(실제 = iris$Species, 예측 = pred)   # 혼동행렬


# ---------------------------------------------------------------------
# 9. 군집 분석
# ---------------------------------------------------------------------
x <- scale(iris[, 1:4])                  # 표준화(단위를 맞춤). 품종 열(5번째)은 빼고 사용

# (1) 계층적 군집 + 덴드로그램
hc <- hclust(dist(x), method = "ward.D2")   # dist = 유클리드 거리, 와드 연결법
plot(hc, labels = FALSE, main = "덴드로그램")
rect.hclust(hc, k = 3)                   # 3개 군집으로 자르기

# (2) K-means
set.seed(1)                              # 결과 재현용(초깃값 고정). K-means는 초깃값에 따라 결과가 달라짐!
km <- kmeans(x, centers = 3)
table(군집 = km$cluster, 실제품종 = iris$Species)


# ---------------------------------------------------------------------
# 10. 주성분 분석 (PCA)
# ---------------------------------------------------------------------
pca <- prcomp(iris[, 1:4], scale. = TRUE)
summary(pca)
# "Cumulative Proportion"(누적 기여율) 행을 보세요.
#  PC2까지 약 0.96 → 주성분 2개로 원래 정보의 96%를 설명 → 2개면 충분
screeplot(pca, type = "lines")           # 꺾이는 지점(elbow) 확인


# ---------------------------------------------------------------------
# 11. 연관 분석 지표 손 계산 (예: 거래 10건)
# ---------------------------------------------------------------------
전체 <- 10; 빵 <- 6; 우유 <- 4; 빵과우유 <- 3
지지도 <- 빵과우유 / 전체
신뢰도 <- 빵과우유 / 빵
향상도 <- 신뢰도 / (우유 / 전체)
c(지지도 = 지지도, 신뢰도 = 신뢰도, 향상도 = 향상도)   # 0.3, 0.5, 1.25
# 실제 분석은 arules 패키지의 apriori() 함수 사용: install.packages("arules")


# ---------------------------------------------------------------------
# 12. 시계열 맛보기 (AirPassengers: 1949~1960 월별 항공 승객 수)
# ---------------------------------------------------------------------
plot(AirPassengers)                      # 추세↑ + 계절성 + 분산도 커짐 → 비정상 시계열
plot(decompose(AirPassengers))           # 추세 / 계절 / 불규칙 요인으로 분해
ap <- diff(log(AirPassengers))           # 로그 변환(분산 안정) + 차분(평균 안정)
plot(ap)                                 # 평균이 일정해 보임 → 정상성에 가까워짐
acf(ap); pacf(ap)                        # ACF, PACF 그래프 (AR/MA 차수 판단용)
